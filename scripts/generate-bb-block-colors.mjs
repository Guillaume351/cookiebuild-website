#!/usr/bin/env node
// Precomputes the compact texture -> average color map used by the Build Battle
// share-card renderer (server/buildbattle/og-render.ts) from the BlueMap texture
// atlas shipped with the 3D map viewer. Run after updating textures.json:
//   node scripts/generate-bb-block-colors.mjs
import { readFileSync, writeFileSync } from "node:fs";

const source = new URL(
  "../public/map-viewer/maps/buildbattles_legacy_buildbattles/textures.json",
  import.meta.url,
);
const textures = JSON.parse(readFileSync(source, "utf8"));
const byte = (value) => Math.max(0, Math.min(255, Math.round(Number(value) * 255)));
const entries = textures
  .filter((texture) => typeof texture.resourcePath === "string" && texture.resourcePath.startsWith("minecraft:block/"))
  .map((texture) => {
    const [r, g, b, a] = texture.color;
    const packed = ((byte(r) << 24) | (byte(g) << 16) | (byte(b) << 8) | byte(a)) >>> 0;
    return [texture.resourcePath.slice("minecraft:block/".length), packed];
  })
  .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0));

// One "name=rrggbbaa" pair per entry, joined: about half the size of an object literal.
const encoded = entries.map(([name, packed]) => `${name}=${packed.toString(16).padStart(8, "0")}`).join(";");
const output = `// Generated by scripts/generate-bb-block-colors.mjs from
// public/map-viewer/maps/buildbattles_legacy_buildbattles/textures.json.
// Average RGBA color of each minecraft:block/* texture. Do not edit by hand.
export const BB_TEXTURE_COLORS_ENCODED =
  ${JSON.stringify(encoded)};
`;
writeFileSync(new URL("../server/buildbattle/block-colors.generated.ts", import.meta.url), output);
console.log(`Wrote ${entries.length} texture colors`);
