#!/usr/bin/env node
// Regenerates shared/buildbattle-themes.ts from the BuildBattles plugin
// bundles (bb.theme.name.* keys). Usage:
//   node scripts/generate-bb-theme-names.mjs <path to BuildBattles/src/main/resources>
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const resources = process.argv[2];
if (!resources) {
  console.error("Usage: node scripts/generate-bb-theme-names.mjs <BuildBattles resources directory>");
  process.exit(1);
}

function parseProperties(text) {
  const values = {};
  const lines = text.replace(/\r\n?/g, "\n").split("\n");
  for (let index = 0; index < lines.length; index += 1) {
    let line = lines[index].replace(/^\s+/, "");
    if (!line || line.startsWith("#") || line.startsWith("!")) continue;
    while (/(^|[^\\])(\\\\)*\\$/.test(line) && index + 1 < lines.length) {
      line = line.slice(0, -1) + lines[++index].replace(/^\s+/, "");
    }
    const match = /^((?:\\.|[^:=\s])+)\s*[:=\s]\s*(.*)$/.exec(line);
    if (!match) continue;
    const unescape = (value) => value
      .replace(/\\u([0-9a-fA-F]{4})/g, (_, hex) => String.fromCharCode(Number.parseInt(hex, 16)))
      .replace(/\\([tnrf])/g, (_, c) => ({ t: "\t", n: "\n", r: "\r", f: "\f" })[c])
      .replace(/\\(.)/g, "$1");
    values[unescape(match[1])] = unescape(match[2]);
  }
  return values;
}

const LOCALE_BY_SUFFIX = { pt_BR: "pt-BR" };
const names = {};
for (const file of readdirSync(resources).sort()) {
  const match = /^buildbattles_messages_([A-Za-z_]+)\.properties$/.exec(file);
  if (!match) continue;
  const locale = LOCALE_BY_SUFFIX[match[1]] ?? match[1];
  const properties = parseProperties(readFileSync(join(resources, file), "utf8"));
  for (const [key, value] of Object.entries(properties)) {
    const theme = /^bb\.theme\.name\.([a-z0-9_]+)$/.exec(key)?.[1];
    if (!theme || !value.trim()) continue;
    (names[theme] ??= {})[locale] = value.trim();
  }
}

const sorted = Object.fromEntries(Object.keys(names).sort().map((theme) => [
  theme,
  Object.fromEntries(Object.keys(names[theme]).sort().map((locale) => [locale, names[theme][locale]])),
]));
const output = `// Generated by scripts/generate-bb-theme-names.mjs from the BuildBattles plugin
// bundles (bb.theme.name.*). Do not edit by hand.
export const BUILDBATTLE_THEME_NAMES: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(sorted, null, 2)};
`;
writeFileSync(new URL("../shared/buildbattle-themes.ts", import.meta.url), output);
console.log(`Wrote ${Object.keys(sorted).length} themes`);
